"""Состояние диалога между репликами абонента.

ЗАЧЕМ ОНО ПОНАДОБИЛОСЬ ИМЕННО СЕЙЧАС

Правило 4.7 требует подтверждения абонента перед любой записью. Между «система
показала черновик» и «абонент подтвердил» проходит отдельный HTTP-запрос —
значит кто-то должен помнить черновик. Без этого регистрация обращения из
диалога невозможна в принципе, а не «сделана упрощённо».

Подтверждение приходит **обычной репликой** в `POST /v1/generate`, а не своим
адресом: правило 4.4 разрешает ровно два адреса, и диаграмма последовательностей
Этапа 2 описывает именно такой ход. Отсюда и требование к этому модулю — узнать
сессию по `session_id` из метаданных запроса.

ЗДЕСЬ ВПЕРВЫЕ ХРАНЯТСЯ ПЕРСОНАЛЬНЫЕ ДАННЫЕ АБОНЕНТА

В состоянии лежат слоты: ФИО, лицевой счёт, основание, — и текст черновика. До
сих пор прототип ПДн не хранил вовсе: вопрос уходил обезличенным и нигде не
оседал. Это меняется, и потому:

* **срок жизни задан** (`session_ttl_seconds`) — он же единственный механизм
  удаления. Пункт 18 сведённого TODO требует назвать срок хранения диалогов;
  здесь он назван для прототипа, на MVP его называет владелец;
* хранилище — Redis без сохранения на диск (раздел 48.4): на прототипе это
  рабочая память, переживать перезапуск ей незачем;
* **на MVP так нельзя**: там состояние сессии обязано переживать перезапуск, а
  значит появится и постоянное хранилище, и вопрос его защиты.

ПОЧЕМУ НЕДОСТУПНОСТЬ ХРАНИЛИЩА — НЕ `503`

ADR-008 отвечает `503` при отказе хранилища **лимитов**, и довод там денежный:
пропуск запросов снял бы защиту ровно в тот момент, когда она нужна. С сессиями
иначе. Потеря состояния не открывает дыру, а закрывает путь: без состояния
обращение никогда не окажется в `AWAITING_CONFIRMATION`, и запись не выполнится.
Правило 4.7 остаётся выполненным **по построению**.

Поэтому отказ хранилища здесь вырождается в «сессии нет»: вопрос без записи
по-прежнему получает ответ, а попытка подтвердить получает честное «черновик не
найден» вместо молчания. Отвечать `503` на вопрос о пени из-за недоступного
Redis значило бы уронить работающий путь ради неработающего.
"""

from __future__ import annotations

import logging
from typing import Any

from app.models import SessionState

__all__ = ["SessionStore", "SubscriberMismatch"]

logger = logging.getLogger(__name__)

KEY_PREFIX = "session:"


class SubscriberMismatch(RuntimeError):
    """Сессию запросил не тот абонент, которому она принадлежит.

    Это угрозы Spoofing и IDOR из разбора безопасности: подменив `session_id` в
    запросе, можно было бы прочитать чужой черновик — с ФИО и лицевым счётом — и
    подтвердить операцию по чужому счёту.

    Проверка стоит **здесь**, при загрузке, а не только в гейтах адаптера: до
    адаптера чужое состояние успело бы попасть в ответ абоненту. Гейт адаптера
    при этом остаётся — он защищает путь записи, если тот вызовут напрямую.
    """

    def __init__(self, session_id: str) -> None:
        # Идентификаторы в сообщение не попадают: сопоставление двух чужих
        # значений в журнале — уже сведение данных (тот же довод, что в
        # `app/adapters/base.py`).
        super().__init__(f"сессия {session_id!r} принадлежит другому абоненту")
        self.session_id = session_id


class SessionStore:
    """Состояние диалога в Redis.

    :param client: клиент Redis. `None` — состояние не хранится вовсе; сервис
        при этом работает, но регистрация обращения недоступна.
    :param ttl_seconds: срок жизни состояния.
    """

    def __init__(self, client: Any | None, *, ttl_seconds: int) -> None:
        self._client = client
        self._ttl = ttl_seconds

    @staticmethod
    def _key(session_id: str) -> str:
        return f"{KEY_PREFIX}{session_id}"

    def load(self, session_id: str, subscriber_id: str) -> SessionState:
        """Достать состояние или завести новое.

        Новое состояние — не признак ошибки: первая реплика диалога, истёкший
        срок, недоступный Redis выглядят одинаково и обрабатываются одинаково.
        Разницу видит вызывающий: у нового состояния нет черновика, и
        подтверждать нечего.

        :raises SubscriberMismatch: сессия принадлежит другому абоненту.
        """
        raw = None
        if self._client is not None:
            try:
                raw = self._client.get(self._key(session_id))
            except Exception as exc:  # noqa: BLE001 — любой отказ хранилища
                # Не `503`: см. разбор в шапке модуля. Путь записи закрывается
                # сам, путь ответа продолжает работать.
                logger.warning(
                    "состояние сессии недоступно (%s): диалог начнётся заново", exc
                )

        if raw is None:
            return SessionState(session_id=session_id, subscriber_id=subscriber_id)

        session = SessionState.model_validate_json(raw)
        if session.subscriber_id != subscriber_id:
            raise SubscriberMismatch(session_id)
        return session

    def save(self, session: SessionState) -> None:
        """Сохранить состояние, продлив срок жизни.

        Срок отсчитывается от последней реплики, а не от начала диалога: абонент,
        который думает над черновиком дольше срока, иначе терял бы его на
        полуслове.
        """
        if self._client is None:
            return
        try:
            self._client.set(
                self._key(session.session_id),
                session.model_dump_json(),
                ex=self._ttl,
            )
        except Exception as exc:  # noqa: BLE001
            # Молча терять состояние нельзя: следующая реплика получит «черновик
            # не найден», и без этой записи причина будет неизвестна.
            logger.warning("состояние сессии не сохранено (%s)", exc)

    def drop(self, session_id: str) -> None:
        """Забыть состояние — после завершения обращения.

        Зовётся, когда диалог дошёл до конца: держать ПДн дольше, чем они нужны,
        незачем, а срок жизни — верхняя граница, не замена уборке.
        """
        if self._client is None:
            return
        try:
            self._client.delete(self._key(session_id))
        except Exception as exc:  # noqa: BLE001
            logger.warning("состояние сессии не удалено (%s)", exc)
