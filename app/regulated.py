"""Реестр регламентных ответов — текстов, которые обязаны не меняться (ADR-100).

Тема распознана — ответ берётся отсюда и отдаётся дословно, без обращения к
модели. Правило шире одного случая: **текст, который обязан не меняться, не
производится языковой моделью.** Причина не в настройке температуры: провайдер
меняет версию модели без нашего участия, а проект вдобавок переключает
провайдера автоматически при сбое (проверено живым прогоном).
Формулировка, дословность которой зависит от того, кто сегодня ответил,
дословностью не является.

ПОЧЕМУ РЕЕСТР ЖИВЁТ ЗДЕСЬ, А НЕ В БАЗЕ ЗНАНИЙ

База знаний обязана **меняться**: delta-индексация, версии, blue-green. Реестр
обязан **не меняться**. Один механизм для двух противоположных требований —
плохая опора, и второе подчинилось бы первому. Поэтому реестр лежит рядом с
таксономией: это справочник, а не документ.

ПОЧЕМУ ОТВЕТЧИК ЖИВЁТ В BACKEND, А НЕ В ШЛЮЗЕ

Прежняя редакция помещала реестр внутрь шлюза — тогда
это было единственное место, где вообще собирался ответ. С появлением Backend выбор пути ответа
переехал туда, куда его относит архитектура,
а из шлюза удалено всё предметное. Класть реестр обратно в шлюз значило бы
вернуть отступление, ради устранения которого Backend и появился.

ЧТО К ЭТОМУ ПУТИ ПРИМЕНЯЕТСЯ, А ЧТО НЕТ (ADR-100, разобрано явно)

======================== ====================================================
 Лимиты                   **Да.** Иначе появляется путь в обход лимитов
 Обезличивание запроса    Нет: наружу ничего не уходит, защищать нечего
 Обращение к модели       Нет: в этом и состоит решение
 Guardrails на ответе     **Нет.** Проверять утверждённый норматив нашими
                          правилами — ставить фильтр выше норматива
======================== ====================================================

Проверки не отменены, а сдвинуты ко входу: формулировка проходит их один раз при
внесении в реестр, а не на каждом ответе.

ТЕКСТ ПРОТОТИПА НАШ, И ЭТО ПОМЕЧЕНО, А НЕ УМОЛЧАНО

Владелец систем передать формулировку не смог, и решено написать её самим
(4 сентября 2026). Дисциплина здесь та же, что с синтетическими кодами типов
обращений: **наш текст, принятый за утверждённый, — та же ошибка в другом
материале.** Поэтому у записи есть поле `approved`, оно `False`, и строгий режим
загрузки не даёт неутверждённой записи уехать дальше прототипа.

Содержание выбрано так, чтобы **ничего не утверждать за владельца**. Заявление
«вода соответствует нормативам» — утверждение о безопасности водоснабжения; наше
собственное, оно было бы ровно тем, от чего предостерегает ADR-100. Поэтому
текст **направляет**: называет, кто ведёт контроль, где опубликованы его
результаты и куда обратиться за сведениями по адресу. Всё это проверяемо, и
заменить его на утверждённую формулировку — правка одной строки данных.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from datetime import date, datetime

from app.backend.orchestrator import DirectAnswer
from app.models import GenerateRequest
from app.taxonomy import Topic

__all__ = [
    "PROTOTYPE_REGISTRY",
    "RegulatedAnswer",
    "RegulatedResponder",
    "UnapprovedAnswerError",
]

logger = logging.getLogger(__name__)


class UnapprovedAnswerError(RuntimeError):
    """Неутверждённая формулировка при строгой загрузке реестра.

    Отдельная ошибка, а не пропуск записи: молча выключенный регламентный ответ
    отправил бы вопрос о качестве воды на генерацию — то есть ровно туда, откуда
    решение ADR-100 его и убирало.
    """

    def __init__(self, topic: Topic) -> None:
        super().__init__(
            f"регламентный ответ для темы {topic.value!r} не утверждён владельцем: "
            "на прототипе это допустимо, вне прототипа — нет (ADR-100)"
        )
        self.topic = topic


@dataclass(frozen=True, slots=True)
class RegulatedAnswer:
    """Запись реестра.

    :param topic: тема, на которую отвечает запись.
    :param template: текст. Подстановка ровно одна — `{phone}`; см. ниже.
    :param source: откуда взята формулировка.
    :param owner: кто вправе её менять.
    :param effective_from: дата вступления в силу; ``None`` — не утверждена.
    :param approved: утверждена ли владельцем.

    **Почему шаблон, а не готовая строка.** Номер контакт-центра уже живёт в
    настройках, и тот же номер стоит в базе знаний; третий его экземпляр здесь
    разошёлся бы с остальными при первой правке — этот класс ошибки проект
    проходил трижды. Подстановка одна и
    единственная: у значения один источник.
    """

    topic: Topic
    template: str
    source: str
    owner: str
    effective_from: date | None = None
    approved: bool = False

    def render(self, *, phone: str) -> str:
        return self.template.format(phone=phone)


WATER_QUALITY = RegulatedAnswer(
    topic=Topic.WATER_QUALITY,
    template=(
        "Качество питьевой воды контролирует производственная лаборатория "
        'ООО "РВК-Воронеж". Результаты контроля публикуются в разделе раскрытия '
        "информации на сайте: "
        "https://voronezh.rosvodokanal.ru/about/open_info/standarts/water_supply/ — "
        "раскрытие ведётся по стандартам, утверждённым Постановлением "
        "Правительства РФ от 17.01.2013 № 6.\n\n"
        "Чтобы получить сведения по конкретному адресу или заказать анализ воды, "
        "обратитесь в контакт-центр {phone}."
    ),
    source=(
        "Наша формулировка (4 сентября 2026). Владельцем не утверждена. "
        "Ссылка на раздел раскрытия и номер постановления сверены с сайтом "
        "voronezh.rosvodokanal.ru, а не взяты по памяти."
    ),
    owner="не назначен",
    effective_from=None,
    approved=False,
)
"""Первая и пока единственная запись реестра.

Текст **направляет, а не утверждает**: он не заявляет, что вода соответствует
нормативам. Такое заявление — утверждение о безопасности водоснабжения, и делать
его за владельца нельзя (ADR-100 предостерегает ровно от этого). Когда владелец
передаст свою формулировку, заменяется `template`, проставляются `owner`,
`effective_from` и `approved` — и больше ничего.
"""

PROTOTYPE_REGISTRY: tuple[RegulatedAnswer, ...] = (WATER_QUALITY,)


class RegulatedResponder:
    """Отдаёт регламентный ответ, если тема есть в реестре.

    :param registry: записи реестра.
    :param phone: номер контакт-центра для подстановки.
    :param strict: не допускать неутверждённых записей.

    ``strict`` по умолчанию **включён**: неутверждённая формулировка не должна
    уезжать дальше прототипа незаметно. Прототип поднимается с ``strict=False``
    и пишет предупреждение в журнал — та же видимая дыра, что у пустой базы
    знаний.
    """

    def __init__(
        self,
        registry: tuple[RegulatedAnswer, ...] = PROTOTYPE_REGISTRY,
        *,
        phone: str,
        strict: bool = True,
    ) -> None:
        for answer in registry:
            if answer.approved:
                continue
            if strict:
                raise UnapprovedAnswerError(answer.topic)
            logger.warning(
                "регламентный ответ для темы %s не утверждён владельцем: "
                "текст наш, до утверждения он годится только для прототипа",
                answer.topic.value,
            )
        self._by_topic = {answer.topic: answer for answer in registry}
        self._phone = phone

    def answer(self, request: GenerateRequest, *, now: datetime) -> DirectAnswer | None:
        """``None`` — тема не наша, запрос идёт обычным путём.

        Время не используется: регламентный текст на то и регламентный, что от
        даты не зависит. Параметр в подписи — требование протокола `DirectResponder`,
        общего с ответчиком отключений, которому время нужно.
        """
        topic = request.metadata.topic
        if topic is None:
            # Тема не проставлена: классификация до оркестратора не дошла.
            # Отвечать регламентным текстом наугад нельзя — «не мой случай».
            return None
        entry = self._by_topic.get(topic)
        if entry is None:
            return None
        return DirectAnswer(text=entry.render(phone=self._phone))
