"""Классификация обращения: тема ответа и тип для регистрации.

Возвращает значения **двух осей** (ADR-011), и обе получают значение, даже если
распознать не удалось: неизвестного значения на выходе не бывает. Это требование
шага 6 плана разработки — «ни один путь возврата типа обращения не выдаёт
значения вне справочника», — и оно закрывает дефект 11.8, где запасная ветка
прототипа отдавала транслитерацию `prochee` вместо кода.

ПОЧЕМУ ТЕМА ОПРЕДЕЛЯЕТСЯ ПРАВИЛАМИ, А НЕ МОДЕЛЬЮ

Тема решает, **звать ли модель вообще**: `outage` уходит на точный поиск по
графику, `water_quality` — на утверждённую формулировку, и оба минуют генерацию
(ADR-012, ADR-013). Определять её моделью значило бы звать модель, чтобы узнать,
звать ли модель, — и платить за это дважды на каждом запросе, включая те, где
она не нужна.

Правил хватает: тем всего три, и две из них узнаются по прямым признакам —
«нет воды», «отключение», «качество воды». Это не упрощение, а следствие того,
что тема выражает намерение, а не предмет.

ПОЧЕМУ ТИП ОБРАЩЕНИЯ — ПОКА ТОЛЬКО ПО КЛЮЧЕВЫМ СЛОВАМ

Тип нужен для регистрации (Этап 2) и для разбивки метрик. На Этапе 1 **ничего не
регистрируется**, поэтому единственный его потребитель — метрика, и лишний вызов
модели ради разбивки графика удвоил бы задержку и стоимость каждого ответа.

Замер запасного режима: охват 75%, точность 65% там, где сигнал есть (раздел
56.11). Для метрики достаточно; для регистрации — нет, и к Этапу 2 сюда
добавится режим с моделью. Место для него оставлено: :meth:`Triage.classify`
принимает готовый тип извне.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from app.taxonomy import InquiryType, Topic, classify_by_keywords, coerce, coerce_topic

__all__ = ["TOPIC_MARKERS", "Triage", "TriageResult"]


TOPIC_MARKERS: dict[Topic, tuple[str, ...]] = {
    Topic.OUTAGE: (
        "нет воды",
        "нет холодной воды",
        "нет горячей воды",
        "отключили воду",
        "отключение воды",
        "отключения воды",
        "когда включат",
        "когда дадут воду",
        "отсутствует водоснабжение",
    ),
    Topic.WATER_QUALITY: (
        "качество воды",
        "качества воды",
        "цвет воды",
        "мутная вода",
        "мутную воду",
        "ржавая вода",
        "запах воды",
        "вода с запахом",
    ),
}
"""Признаки тем, узнаваемых до обращения к модели.

Слово «авария» сюда намеренно **не входит**, хотя выглядит подходящим. В базе
знаний есть вопрос «Что делать, если прибор учета вышел из строя из-за аварии на
внутренних сетях» — это про счётчик, а не про отсутствие воды, и по одному слову
его увело бы на график отключений.

Признаки составные, а не однословные, по той же причине: «вода» встречается в
каждом втором обращении к водоканалу и различать не может ничего."""


@dataclass(frozen=True, slots=True)
class TriageResult:
    """Итог классификации. Оба значения всегда из справочника."""

    topic: Topic
    inquiry_type: InquiryType
    matched_by: str
    """Чем распознана тема: `rule`, `metadata` или `default`.

    Нужно не для отладки: доля `default` показывает, как часто классификация
    ничего не дала, и без разбивки она неотличима от доли настоящих общих
    вопросов."""

    @property
    def needs_model(self) -> bool:
        """Пойдёт ли запрос к модели.

        `outage` и `water_quality` отвечаются без неё по противоположным
        причинам: график меняется постоянно, регламентная формулировка не
        меняется вовсе.
        """
        return self.topic is Topic.GENERAL


class Triage:
    """Тонкая обёртка над справочником и ключевыми словами.

    Тяжёлого фреймворка агентов здесь нет намеренно: вся логика состояний живёт
    в автомате шага 2, а классификация — это разбор строки, а не сценарий.
    """

    def classify(
        self,
        query: str,
        *,
        topic: Topic | None = None,
        inquiry_type: InquiryType | None = None,
    ) -> TriageResult:
        """Определить тему и тип обращения.

        :param topic: уже известная тема — например, пришедшая в метаданных
            запроса. Классификация её не переопределяет: пришедшее снаружи
            значение считается более осведомлённым, чем разбор строки.
        :param inquiry_type: то же для типа. Место для будущего режима с
            моделью: он проставит тип до вызова, а этот метод его сохранит.
        """
        if topic is not None:
            return TriageResult(topic, coerce(inquiry_type), "metadata")

        detected = self._topic_by_rules(query)
        if detected is not None:
            return TriageResult(detected, self._type(query, inquiry_type), "rule")

        return TriageResult(Topic.GENERAL, self._type(query, inquiry_type), "default")

    @staticmethod
    def _topic_by_rules(query: str) -> Topic | None:
        """Первая тема, чей признак встретился. Порядок перебора устойчив.

        Совпадение сразу с двумя темами возможно («нет воды и качество плохое»),
        и выбор первого — осознанное упрощение: тем всего три, а спрашивать
        уточнение ради редкого случая дороже, чем ошибиться в нём.
        """
        lowered = re.sub(r"\s+", " ", query.strip().lower().replace("ё", "е"))
        for topic, markers in TOPIC_MARKERS.items():
            if any(marker in lowered for marker in markers):
                return topic
        return None

    @staticmethod
    def _type(query: str, given: InquiryType | None) -> InquiryType:
        """Тип обращения: переданный, распознанный или `other`.

        Через :func:`coerce` проходит всё — и переданное снаружи тоже. Значение
        вне справочника отсюда выйти не может ни по одному пути; ровно это
        требует шаг 6 плана и ровно это нарушала запасная ветка прототипа
        (дефект 11.8).
        """
        if given is not None:
            return coerce(given)
        codes = classify_by_keywords(query)
        # Неоднозначность — свойство текста: каждый пятый настоящий текст даёт
        # больше одного кода (раздел 56.11). Берётся первый, а не отбрасываются
        # все: для метрики приблизительный тип полезнее отсутствующего.
        return codes[0] if codes else InquiryType.OTHER


def coerce_result(topic: object, inquiry_type: object) -> TriageResult:
    """Собрать итог из чужих значений, приведя оба к справочнику.

    Нужен там, где тема и тип приходят из внешнего источника — из метаданных
    запроса или из ответа модели на Этапе 2.
    """
    return TriageResult(coerce_topic(topic), coerce(inquiry_type), "metadata")  # type: ignore[arg-type]
