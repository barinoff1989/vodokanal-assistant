"""Классификация обращения: тема ответа и тип для регистрации.

Возвращает значения **двух осей** (ADR-300), и обе получают значение, даже если
распознать не удалось: неизвестного значения на выходе не бывает. Это требование
проекта — «ни один путь возврата типа обращения не выдаёт
значения вне справочника», — и оно закрывает дефект прошлого прототипа, где запасная ветка
прототипа отдавала транслитерацию `prochee` вместо кода.

ПОЧЕМУ ТЕМА ОПРЕДЕЛЯЕТСЯ ПРАВИЛАМИ, А НЕ МОДЕЛЬЮ

Тема решает, **звать ли модель вообще**: `outage` уходит на точный поиск по
графику, `water_quality` — на утверждённую формулировку, и оба минуют генерацию
(ADR-100). Определять её моделью значило бы звать модель, чтобы узнать,
звать ли модель, — и платить за это дважды на каждом запросе, включая те, где
она не нужна.

Правил хватает: тем всего три, и две из них узнаются по прямым признакам —
«нет воды», «отключение», «качество воды». Это не упрощение, а следствие того,
что тема выражает намерение, а не предмет.

ПОЧЕМУ ТИП ОБРАЩЕНИЯ — ПО КЛЮЧЕВЫМ СЛОВАМ, А ЗАПАСНОЙ ПУТЬ — ТОЛЬКО НА СЕМЬ
ИЗ ШЕСТНАДЦАТИ

Тип нужен для регистрации (`Registrar.offer`) и для разбивки метрик. Замер
запасного режима по ключевым словам: охват 75%, точность 65% там, где сигнал
есть — для метрики достаточно, для регистрации мало.

`classify_async` добавляет запасной классификатор эмбеддингами
(`app/agents/inquiry_type_fallback.py`), но только на семь типов из
`REGISTRABLE` — тех, по которым регистрация вообще предлагается. Остальные
девять на прототипе не запускают действие (их потребитель — только метрика),
а разбор реальных текстов показал, что там смешаны споры и заявки, для
которых у модели нет надёжного примера (см. заголовок того модуля).
"""

