"""Консультант: решает, есть ли на чём отвечать.

Одно правило: **при пустом контексте
генерация не вызывается**. Порог поиска говорит то же с другой стороны — ниже
порога близости контекст считается не найденным, и включается запасной путь без
модели.

ПОЧЕМУ ЭТО ВАЖНЕЕ, ЧЕМ КАЖЕТСЯ. Модель без контекста не молчит — она отвечает.
Отвечает связно, уверенно и на общих сведениях о водоснабжении, которых в
регламентах водоканала может не быть вовсе. Абонент получит правдоподобный
вымысел со ссылкой на несуществующий порядок, и отличить его от настоящего
ответа не сможет ни он, ни мы.

Отказ здесь — не ухудшение ответа, а единственный честный ответ. Он же дешевле:
запрос без контекста не тратит ни токенов, ни ожидания.

ЗАПАСНОЙ ОТВЕТ НАЗЫВАЕТ КОНТАКТ-ЦЕНТР. «Не знаю» без продолжения оставляет
абонента там же, где он был. Номер берётся из настроек, а не из текста ответа:
он же встречается в базе знаний, и два источника одного номера разойдутся при
первой правке — этот класс ошибки проект проходил трижды.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from app.models import ContextChunk

__all__ = ["Advisor", "NO_CONTEXT_ANSWER"]

NO_CONTEXT_ANSWER = (
    "По этому вопросу у меня нет сведений в базе знаний, и я не буду отвечать "
    "наугад. Обратитесь, пожалуйста, в контакт-центр по телефону {phone} — там "
    "помогут разобраться."
)
"""Текст отказа. Заполняется номером из настроек."""


@dataclass(frozen=True, slots=True)
class Advice:
    """Решение консультанта."""

    answer: str | None
    """Готовый ответ, если генерация не нужна. ``None`` — идти к модели."""

    @property
    def needs_model(self) -> bool:
        return self.answer is None


@dataclass(frozen=True, slots=True)
class Advisor:
    """Тонкая обёртка: смотрит на контекст и решает, звать ли модель.

    :param contact_phone: телефон контакт-центра для запасного ответа.
    """

    contact_phone: str

    def advise(self, context: Sequence[ContextChunk]) -> Advice:
        """``None`` в ответе означает «контекст есть, зови модель»."""
        if context:
            return Advice(answer=None)
        return Advice(answer=NO_CONTEXT_ANSWER.format(phone=self.contact_phone))
