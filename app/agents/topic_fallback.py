"""Ниже — тема не найдена. [ПРЕДПОЛОЖЕНИЕ], проверенное на пробе из полутора
десятков вопросов, не на размеченном корпусе.

**Первая цифра (0.80) не прошла проверку.** «Спасибо за помощь» дала 0.8687
до темы `template`, «здравствуйте, подскажите пожалуйста» — 0.8932 до неё же:
короткие фразы на этом языке и в этом домене (вода, счета, заявления) вообще
не разделяются низким порогом — та же находка, что сделана для
`score_threshold` поиска. Оба целевых случая сессии дают
0.94–0.95 — 0.90 отсекает пустые совпадения и пропускает их."""

TOPIC_MATCH_MARGIN = 0.05
"""Насколько лучшая тема обязана опережать вторую (другую) по близости.

Без разрыва предпочтение между двумя темами — вопрос третьего знака после
запятой, а не сигнал: «почём кубометр воды» дал `outage` вместо `tariff` с
разрывом 0.0053 — ошибка, которую разрыв и должен ловить.

**Поднято с 0.03 до 0.05 .** «Как подключить воду в дом?»
прошла и порог, и прежний разрыв: 0.9092 до примера `outage` «Когда включат
воду в доме?» против 0.8791 до ближайшего `template` — разрыв 0.0301, только
на волосок выше прежнего 0.03. «Подключить» и «включат» — общий корень
«-ключ-», модель их путает при почти дословном совпадении остальных слов
(«воду», «в доме»/«в дом»). Разрыв один не спас: добавление точного примера
`template` подняло лучшую тему до 0.9553, но и `outage`-пример остался рядом
(0.9092) — разрыв 0.0461, чуть ниже даже нового порога. Помогла перефразировка
самого коллизионного примера — «Когда включат воду в доме?» →
«Когда закончится отключение и вода вернётся?» — та же тема без слова с
корнем «-ключ-»: развод по формулировке, а не подгонка числа. С обеими
правками 0.05 отсекает исходную ошибку и держит все подтверждённые случаи
(0.0627–0.0975). [ПРЕДПОЛОЖЕНИЕ]."""


