_NON_DIGIT = re.compile(r"\D")


def is_public_information(entity_type: str, fragment: str) -> bool:
    """Опубликованные организацией сведения, а не персональные данные.

    :param entity_type: тип найденной сущности.
    :param fragment: сам найденный фрагмент.

    Применяется **после** распознавания и только к тем типам, у которых бывает
    публичный вариант: телефон, почта, место и название организации. Лицевой
    счёт, СНИЛС и ИНН сюда не входят — публичными они не бывают, а если такой
    номер встретится в ответе, его и надо скрыть.
    """
    value = fragment.strip()
    if entity_type == "PHONE_NUMBER":
        digits = _NON_DIGIT.sub("", value)
        # Междугородний код России записывают и как 8, и как +7.
        if digits.startswith("7") and len(digits) == 11:
            digits = "8" + digits[1:]
        return digits in PUBLIC_PHONES
    if entity_type == "EMAIL_ADDRESS":
        return value.lower() in PUBLIC_EMAILS
    if entity_type in ("LOCATION", "PERSON"):
        return value.lower() in PUBLIC_TERMS
    return False


_SENTENCE_START = re.compile("(?:^|[.!?…]\\s+|\\n\\s*)$")
"""Стоит ли фрагмент в начале предложения (смотрим на текст ПЕРЕД ним).

ЗАЧЕМ. Разбор языка помечает именем собственным любое слово с заглавной буквы, а
в начале предложения с заглавной стоит **каждое**. Отсюда «Перерасчёт», «Пункту»,
«Прилагаю», «Согласно», «Добрый» — все они уже перечислены поимённо в `NOT_PII`,
и список пополнялся бы вечно: словарь лечит наблюдённое, а слов в языке больше.

Правило общее и узкое одновременно: снимается **одно слово в начале
предложения**. Настоящее ФИО там стоит либо несколькими словами («Пантелеева
Дарья Сергеевна»), либо не в начале, и такие находки правило не трогает.

Замер на 136 настоящих текстах: снимает 4 находки из 16, все ложные
(«Воронеже» ×2, «Воронеж», «Спасибо»), и сохраняет обе настоящие — ФИО
подрядчика и адрес почты."""

_DIGIT = re.compile(r"\d")
_INNER_PUNCTUATION = re.compile(r"[^\w\s-]", re.UNICODE)
_CYRILLIC = re.compile(r"[а-яёА-ЯЁ]")


def looks_like_pii(
    entity_type: str, fragment: str, *, before: str | None = None
) -> bool:
    """Похож ли найденный разбором языка фрагмент на настоящие данные.

    Проверяется форма, а не смысл: смысл — дело разбора языка, и он уже
    ошибся. Здесь снимаются те ошибки, которые видны по написанию.

    :param entity_type: тип сущности из :data:`PRESIDIO_ENTITIES`.
    :param fragment: сам найденный фрагмент текста.
    :param before: текст, стоящий перед фрагментом. Нужен ровно для одного
        правила — одиночное слово в начале предложения; без него правило
        не применяется, и поведение остаётся прежним.
    """
    if entity_type not in FILTERED_ENTITIES:
        return True

    value = fragment.strip()
    if not value:
        return False

    # Цифры внутри — не имя и не адрес: так к нам попали показания счётчика
    # «ХВ 142,858м3». Номера домов сюда не относятся, их находит не разбор
    # языка, а собственные распознаватели по слову-подсказке.
    if _DIGIT.search(value):
        return False

    # Знаки препинания внутри означают, что границы найдены неверно:
    # «день!Объясните» — два слипшихся слова, а не имя.
    if _INNER_PUNCTUATION.search(value):
        return False

    if not _CYRILLIC.search(value):
        return False

    if _INDUSTRY_ABBREVIATION.match(value):
        return False

    folded = value.casefold()
    if folded in INDUSTRY_TERMS or folded in NOT_PII:
        return False

    # Одиночное слово в начале предложения. Проверка стоит последней: она самая
    # общая, и до неё доходят только фрагменты, не снятые более точными
    # правилами.
    return not (
        before is not None
        and len(value.split()) == 1
        and _SENTENCE_START.search(before) is not None
    )


# --- Общий приём: цифры рядом со словом-подсказкой ---------------------------- #

_HINT_WINDOW = 40
"""Насколько далеко от подсказки может стоять номер. Сорок символов — это
примерно «лицевой счёт для оплаты услуг: 1234567890»; больше брать опасно,
начнут попадать числа из соседнего предложения."""


def _find_near_hint(
    text: str,
    hint: re.Pattern[str],
    digits: re.Pattern[str],
    entity_type: str,
    score: float,
) -> list[PiiSpan]:
    """Найти числа, стоящие рядом со словом-подсказкой.

    Подсказка в тексте — более сильное свидетельство, чем совпадение формата:
    «л/с 9876543210» это лицевой счёт, даже если число случайно проходит
    проверку контрольной суммы ИНН. Поэтому находки по подсказке получают
    более высокую оценку и побеждают при разрешении перекрытий.
    """
    ends = [m.end() for m in hint.finditer(text)]
    if not ends:
        return []
    return [
        PiiSpan(m.start(), m.end(), entity_type, score)
        for m in digits.finditer(text)
        if any(0 <= m.start() - end <= _HINT_WINDOW for end in ends)
    ]


