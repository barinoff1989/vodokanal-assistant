-- Три базы-слепка внешних систем (код-шаг 0).
--
-- Здесь создаются ТОЛЬКО сами базы, без единой таблицы. Это намеренно:
-- разделение по базам отражает тот факт, что в реальности это три
-- независимые системы со своими владельцами, и оно не зависит от того,
-- как устроены их таблицы.
--
-- Схемы таблиц появятся отдельными скриптами после получения CSV-примеров
-- от владельцев систем (Data_Request.md). До этого любая схема была бы
-- гипотезой, а при расхождении переделывать пришлось бы и её, и генератор
-- синтетики, и часть проверок.
--
-- Первая база (billing_stub) создаётся самим образом через POSTGRES_DB,
-- поэтому здесь только две оставшиеся.

-- Личный кабинет: профиль абонента, связь с лицевыми счетами, канал входа.
CREATE DATABASE lk_stub;
COMMENT ON DATABASE lk_stub IS
  'Слепок БД личного кабинета. Синтетика, реальных данных абонентов нет.';

-- Обращения абонентов: тексты, типы, статусы, подразделения-исполнители.
-- Единственный источник реальных формулировок — по нему настраивается
-- классификация и собирается эталонный набор.
CREATE DATABASE inquiries_stub;
COMMENT ON DATABASE inquiries_stub IS
  'Слепок БД обращений. Синтетика, реальных обращений нет.';
