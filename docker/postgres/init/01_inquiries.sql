-- Обращения абонентов, зарегистрированные ассистентом.
--
-- ЧТО ЭТА ТАБЛИЦА ЕСТЬ. На MVP обращение регистрируется в микросервисе
-- обращений владельца через его REST API (ADR-100). На прототипе
-- этого микросервиса нет — закрытая сеть, — и его место занимает эта таблица.
-- Шов проходит по адаптеру `app/adapters/inquiry_service.py`: меняется клиент,
-- а гейты, идемпотентность и всё, что за ними, остаются. То же построение, что
-- у Биллинга (`app/billing/source.py`) и графика отключений.
--
-- ПОЧЕМУ ФАЙЛ ОДИН, А ПРИМЕНЯЕТСЯ ДВАЖДЫ. Postgres выполняет содержимое
-- `docker/postgres/init` только при создании тома: на уже поднятой базе новый
-- файл не сработает. Поэтому тот же файл читает и применяет хранилище при
-- первом обращении. Два места, где пишется схема, разошлись бы при первой
-- правке — этот класс ошибки проект проходил трижды; одно место, применяемое
-- дважды, такого не даёт.

CREATE TABLE IF NOT EXISTS inquiries (
    -- Номер обращения, который видит абонент. Выдаёт база, а не мы: на MVP его
    -- выдаёт микросервис владельца, и разница между «наш» и «их» номером не
    -- должна протекать в код выше адаптера.
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- Ось регистрации (ADR-300). Хранится кодом, а не отображаемым названием:
    -- названия принадлежат владельцу и меняются, коды — наши.
    inquiry_type    TEXT         NOT NULL,

    subscriber_id   TEXT         NOT NULL,
    session_id      TEXT         NOT NULL,

    subject         TEXT         NOT NULL,
    body            TEXT         NOT NULL,

    -- Слоты обращения: ФИО, лицевой счёт, основание. JSONB, а не колонки:
    -- состав слотов зависит от типа обращения, и колонка на каждый слот
    -- превратила бы таблицу в разреженную при первом же новом типе.
    slots           JSONB        NOT NULL DEFAULT '{}'::JSONB,

    -- Ключ идемпотентности из адаптера. UNIQUE — это и есть защита от второй
    -- операции: она не полагается на память процесса, которая перезапуск не
    -- переживает (см. оговорку в `app/adapters/base.py`).
    idempotency_key TEXT         NOT NULL UNIQUE
);

-- Обращения абонента показываются ему в кабинете и разбираются при жалобе,
-- всегда в порядке от свежих.
CREATE INDEX IF NOT EXISTS inquiries_subscriber_created_idx
    ON inquiries (subscriber_id, created_at DESC);
