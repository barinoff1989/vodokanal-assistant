"""Сгенерировать синтетические документы базы знаний — источники 2, 5 и 8.

Настоящих документов на прототипе не будет: регламенты, инструкции и реестр
договоров лежат в закрытой сети (пункт 3 `Data_Request.md`, нужен к MVP). Без
них нечем проверить то, ради чего они и нужны, — **нарезку структурированного
документа на фрагменты**. Двадцать пар FAQ этого не проверяют: одна пара это
один фрагмент, резать там нечего.

ЧТО ЭТИ ФАЙЛЫ ЕСТЬ И ЧЕМ ОНИ НЕ ЯВЛЯЮТСЯ

Это **материал для проверки конвейера**, а не знание. Они годятся, чтобы
измерить, уважает ли чанкинг границы разделов, что делает поиск на документе в
сорок страниц и как ведут себя метаданные. Они **не годятся** для ответа
абоненту: содержание составлено нами.

Дисциплина здесь та же, что с синтетическими кодами типов обращений (журнал,
раздел 55.4) и с неутверждённым текстом о качестве воды (ADR-012):
**синтетический документ, принятый за настоящий, — та же ошибка в другом
материале.** Поэтому пометка стоит в трёх местах сразу:

* первым абзацем каждого документа, крупно и до содержания;
* в свойствах файла (`core_properties.comments` и `category`);
* в колонтитуле каждой страницы — он попадёт и в печать, и в скриншот.

Убрать её одним движением нельзя, и это намеренно.

ЧЕМ СОДЕРЖАНИЕ ВСЁ-ТАКИ ЗАЗЕМЛЕНО

Выдумывать нормативные ссылки нельзя — это ровно тот класс ошибки, который
проект уже ловил у чужих документов (недостоверные цифры, раздел 26.4). Поэтому
берутся **только те пункты, что наблюдались в настоящих материалах** — в ответах
операторов из выгрузки обращений и в публичном FAQ воронежского филиала:
ПП РФ № 354 (пп. 31(1), 32«е», 33«к»(1), 34, 42, 59, 84, 86) и ЖК РФ
(ч. 2 ст. 153, ч. 11 и ч. 14 ст. 155, ч. 1 ст. 157).

Типы обращений берутся из `app/taxonomy.py` — это **настоящий справочник
владельца**, а не наш перечень.

ОТКУДА ОНИ НЕ БЕРУТСЯ

Из корпуса FAQ. Собери мы документы пересказом тех же двадцати пар — и эталонный
набор стал бы находить их «правильно» просто потому, что это тот же текст.
Замер вырос бы, не изменив ничего. Тексты здесь написаны иначе и о другом:
процедуры и условия, а не вопросы-ответы.

ЗАПУСК

    python scripts/generate_kb_docs.py

Пишет в `kb/regulations/` и `kb/contracts/`. Каталог `kb/` исключён из
репозитория, кроме `*.json`: сгенерированное не коммитится — оно
пересобирается.
"""

