def _add_section(document: object, section: Section) -> None:
    document.add_heading(section.heading, level=section.level)  # type: ignore[attr-defined]
    for paragraph in section.paragraphs:
        document.add_paragraph(paragraph)  # type: ignore[attr-defined]
    for bullet in section.bullets:
        document.add_paragraph(bullet, style="List Bullet")  # type: ignore[attr-defined]
    if section.table:
        table = document.add_table(rows=0, cols=len(section.table[0]))  # type: ignore[attr-defined]
        table.style = "Table Grid"
        for row in section.table:
            cells = table.add_row().cells
            for cell, value in zip(cells, row, strict=True):
                cell.text = value


def write_document(spec: Document, root: Path) -> Path:
    from docx import Document as Docx
    from docx.shared import Pt

    document = Docx()
    document.add_heading(spec.title, level=0)
    document.add_paragraph(spec.subtitle)

    # Пометка идёт ДО содержания: читающий не должен добраться до текста, не
    # увидев, что документ синтетический.
    warning = document.add_paragraph()
    run = warning.add_run(SYNTHETIC_MARK)
    run.bold = True
    run.font.size = Pt(11)

    for section in spec.sections:
        _add_section(document, section)

    # Колонтитул: попадёт в печать и в скриншот, где первый абзац уже за кадром.
    for paragraph in document.sections[0].footer.paragraphs:
        paragraph.text = FOOTER_MARK

    properties = document.core_properties
    properties.title = spec.title
    properties.category = "СИНТЕТИКА"
    properties.comments = SYNTHETIC_MARK
    properties.author = "scripts/generate_kb_docs.py"

    path = root / spec.path
    path.parent.mkdir(parents=True, exist_ok=True)
    document.save(str(path))
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-o", "--output", type=Path, default=Path("kb"))
    args = parser.parse_args(argv)

    written = [write_document(spec, args.output) for spec in build_documents()]
    for path in written:
        print(f"  {path}")
    print(f"документов: {len(written)}")
    print(
        "Это материал для проверки нарезки и поиска, а не знание: "
        "содержание составлено нами и для ответа абоненту не годится."
    )
    return 0


