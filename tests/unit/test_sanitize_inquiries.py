"""Проверки приведения выгрузки обращений к одному филиалу.

Прототип обслуживает Воронеж (решение 3 сентября 2026), а в выгрузке
перемешаны филиалы: база знаний берётся с воронежского сайта, график отключений
— по воронежским улицам, и ответ, ссылающийся на сахалинскую организацию, дал бы
абоненту чужие телефоны и чужие адреса центров обслуживания.

Все строки ниже взяты из настоящей выгрузки.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts"))

from sanitize_inquiries import BRANCH_ORG, to_branch  # noqa: E402


@pytest.mark.parametrize(
    "raw",
    [
        'ООО "РВК-Сахалин" направляет по адресу, контролера',
        'ООО "РВК-Архангельск" предоставлены не были',
        "ООО «Краснодар Водоканал» осуществляет подрядная организация",
        # Лишний пробел внутри кавычек — так в выгрузке и записано.
        'ООО " Краснодар Водоканал" документ, подтверждающий право',
        # Потерянная закрывающая кавычка — тоже настоящий случай.
        'предоставить ООО "Краснодар Водоканал, документы можно отправить',
    ],
)
def test_чужой_филиал_приводится_к_воронежскому(raw: str):
    assert BRANCH_ORG in to_branch(raw)
    for city in ("Сахалин", "Архангельск", "Краснодар"):
        assert city not in to_branch(raw)


def test_филиал_которого_не_было_в_списке():
    """Оренбург — настоящий пропуск первой редакции.

    Она перечисляла филиалы по именам, и «ООО "Оренбург Водоканал"» прошло
    насквозь: в списке его не было. Перечень филиалов не закрыт, поэтому шаблон
    берёт **любое** слово с заглавной, а не перечисление.
    """
    assert to_branch('ООО "Оренбург Водоканал" сообщает') == f"{BRANCH_ORG} сообщает"


def test_воронежский_филиал_не_трогается():
    raw = 'представитель ООО "РВК-Воронеж" по телефону'
    assert to_branch(raw) == raw


def test_город_в_адресе_заменяется():
    assert to_branch("г. Тестовый, ул. Набережная, д. 65") == (
        "г. Воронеж, ул. Набережная, д. 65"
    )


def test_падеж_воронежа_не_ломается():
    """«в г. Воронеже» — банковское отделение, город уже нужный.

    Замена превратила бы это в «в г. Воронеж» и сломала падеж, а выигрыша нет.
    """
    raw = "Банка ВТБ (публичное акционерное общество) в г. Воронеже"
    assert to_branch(raw) == raw


def test_служебная_пометка_не_принимается_за_город():
    """В выгрузке под типом «Отмена обращения» есть запись из одного слова
    «Тестовая». Это пометка оператора, а не город: шаблон требует «г.» перед
    названием."""
    assert to_branch("Тестовая") == "Тестовая"


def test_обычный_текст_со_словом_водоканал_не_переписывается():
    """Без заглавной буквы в названии города шаблон срабатывать не должен —
    иначе он начнёт цеплять обычные предложения."""
    raw = "обратитесь в городской водоканал по месту жительства"
    assert to_branch(raw) == raw
