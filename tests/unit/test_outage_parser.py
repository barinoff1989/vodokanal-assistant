"""Проверки разбора графика плановых отключений.

Все случаи взяты из настоящего файла владельца (`tests/data/outage_schedule.txt`,
открытые данные), а не придуманы. Формат нестабилен потому, что файл готовит
человек: схемы у источника нет, и дрейф уже произошёл внутри одного выпуска.

Придуманный тест здесь был бы вреден вдвойне. Он не поймал бы того, что
встречается на самом деле, — а именно на настоящих данных проект уже дважды
находил то, чего не видели проверки (разделы 54.4 и 56.10).
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pytest

from app.outages.parser import (
    Outage,
    normalize_house,
    normalize_street,
    parse_period,
    parse_schedule,
)

FIXTURE = Path(__file__).resolve().parents[1] / "data" / "outage_schedule.txt"
YEAR = 2026


@pytest.fixture(scope="module")
def schedule():
    return parse_schedule(FIXTURE.read_text(encoding="utf-8").splitlines(), year=YEAR)


# --- нормализация улиц ------------------------------------------------------- #


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        # Четыре способа записать тип — все встречаются в одном файле.
        ("ул. Димитрова", "димитрова"),          # префикс
        ("Димитрова", "димитрова"),              # без типа вовсе
        ("Победы б-р", "победы"),                # постфикс
        ("60 Армии ул", "60 армии"),             # постфикс при числовом названии
        ("ул. пер. Цимлянский", "цимлянский"),   # двойной тип
        ("ул. Ленинский пр.", "ленинский"),      # двойной тип другого вида
        ("ул. Наб. Авиастроителей", "авиастроителей"),
        # Разные написания одной улицы обязаны сойтись.
        ("Ленинский пр-т", "ленинский"),
        ("ул. А.Овсеенко", "а овсеенко"),
        ("ул. А. Овсеенко", "а овсеенко"),
        # Тире с пробелами внутри названия.
        ("ул. Порт — Артурская", "порт-артурская"),
        # Регистр и «ё».
        ("Ул. Ленинградская", "ленинградская"),
    ],
)
def test_тип_улицы_снимается_во_всех_четырёх_написаниях(raw: str, expected: str):
    assert normalize_street(raw) == expected


def test_улица_с_названием_как_у_типа_переживает_нормализацию():
    """Главная ловушка этого файла, на которой разбор уже спотыкался.

    «Набережная» — и слово-тип, и название улицы. Снятие типов по словарю
    уничтожало её целиком, и обнаружилось это не рассуждением, а прогоном.
    """
    assert normalize_street("Набережная") == "набережная"
    # Так эта строка приходит разбору: «Набережная, 1, 1а/1» — до первой запятой.
    street_part = "Набережная, 1, 1а/1".partition(",")[0]
    assert normalize_street(street_part) == "набережная"


def test_составное_название_с_типом_сводится_к_одному_виду():
    """Цена правила «последний токен не снимается» — и она осознанна.

    «Спор.» и «Спорт» — два написания одной улицы. Оба сводятся к «набережная»,
    как и отдельная улица Набережная. Слияние заметно и разводится районом, а
    несогласованная нормализация означала бы, что улица не находит сама себя.
    """
    assert normalize_street("ул. Спор. Набережная") == normalize_street("Спорт Набережная")


def test_нормализация_никогда_не_даёт_пустоту(schedule):
    """Пустое название означало бы потерянные адреса без единого следа."""
    assert all(outage.street for outage in schedule)


